const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('../extensions/cocos-creator-mcp-main/node_modules/typescript');
const source = fs.readFileSync(require('node:path').join(__dirname, '../assets/scripts/GuliGame.ts'), 'utf8');
const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, experimentalDecorators: true } }).outputText;
const context = { exports: {}, require: name => name === 'cc' ? { Component: class {}, _decorator: { ccclass: () => value => value } } : {} };
vm.runInNewContext(code, context);
const game = Object.create(context.exports.GuliGame.prototype);
let plays = 0;
game.music = { clip: null, playing: false, play() { plays++; this.playing = true; }, pause() { this.playing = false; }, stop() { this.playing = false; } };
game.enabledInHierarchy = true; game.save = { sound: true, musicVolume: 1, effectsVolume: 1 }; game.screen = 'home';
game.musicClips = { bgm_menu_new: {}, bgm_game_new: {}, bgm_draw_new: {} };
game.syncMusic(); assert.equal(plays, 0); // User gesture required.
game.musicUnlocked = true; game.syncMusic(); assert.equal(plays, 1);
assert.equal(game.music.clip, game.musicClips.bgm_menu_new);
assert.equal(game.music.volume, 0.5);
game.syncMusic(); game.screen = 'collection'; game.syncMusic(); assert.equal(plays, 1);
game.screen = 'game'; game.syncMusic(); assert.equal(plays, 2);
assert.equal(game.music.clip, game.musicClips.bgm_game_new);
assert.equal(game.music.volume, 0.22);
game.save.musicVolume = 0; game.syncMusic(); assert.equal(game.music.playing, false);
game.save.musicVolume = 1; game.syncMusic(); assert.equal(plays, 3);
game.musicHidden = true; game.syncMusic(); assert.equal(game.music.playing, false);
game.musicHidden = false; game.syncMusic(); assert.equal(plays, 4);
game.screen = 'home'; game.syncMusic(); assert.equal(plays, 5);
game.screen = 'gacha'; game.syncMusic(); assert.equal(game.music.clip, game.musicClips.bgm_draw_new);
assert.equal(game.music.volume, 0.22);
game.screen = 'home'; game.syncMusic(); assert.equal(game.music.clip, game.musicClips.bgm_menu_new);
game.enabledInHierarchy = false; game.syncMusic(); assert.equal(game.music.playing, false);
game.enabledInHierarchy = true; game.musicClips = {}; game.syncMusic(); assert.equal(game.music.clip, null);
game.musicClips = { bgm_menu_new: {} }; game.save.musicVolume = 0.4; game.syncMusic(); assert.equal(game.music.volume, 0.2);
const effects = []; game.audio = { playOneShot(clip, volume) { effects.push([clip, volume]); } };
game.clips = { hit: {}, ui_selection: {} }; game.save.effectsVolume = 0.5;
game.sound('hit'); game.sound('ui_selection'); assert.equal(effects[0][1], 0.11); assert.equal(effects[1][1], 0.18);
game.save.effectsVolume = 0; game.sound('hit'); assert.equal(effects.length, 2);
game.volumeSliders = {}; game.modal = 'sound-settings'; let writes = 0; game.persist = () => writes++;
game.down('mouse', -95, 75); assert.equal(game.save.musicVolume, 0);
game.move('mouse', 5, 75); assert.equal(game.save.musicVolume, 0.5);
game.up('mouse', 105, 75); assert.equal(game.save.musicVolume, 1); assert.equal(writes, 1);
game.down('touch:1', -95, -75); assert.equal(game.save.effectsVolume, 0);
game.move('touch:1', 5, -75); assert.equal(game.save.effectsVolume, 0.5);
game.up('touch:1', 105, -75); assert.equal(game.save.effectsVolume, 1); assert.equal(writes, 2);
console.log('PASS music: gesture, menu/collection continuity, gameplay and draw switch, mute, background, return, disable, pending load');
